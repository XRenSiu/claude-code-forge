#!/usr/bin/env python3
"""
convert_v1_to_v2.py — bridge from acceptance-spec's v1 done_when.yaml to the sdlc v2 contract skeleton.

It is a *skeleton*, on purpose: v1 holds test names, not criteria, so the converter cannot invent ACs.
It keeps everything v1 had (behavior → tests-manifest seed, rules, thresholds), moves file/function
existence out into `cards_hint.allowed_files`, and emits one placeholder AC per REQ that
validate_done_when_v2.py will reject until /donewhen-extract (or a human) completes it. The output is
honest about what it does not know.

Usage:
  convert_v1_to_v2.py <done_when.v1.yaml> [--out done_when.yaml] [--spec spec.md]
Exit 0 written · 2 IO error. Prints a summary with the list of ACs that need completion.
"""
import argparse
import datetime as _dt
import json
import re
import sys

try:
    import yaml
except ImportError:
    sys.stderr.write("convert_v1_to_v2.py needs PyYAML\n"); sys.exit(2)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("src"); ap.add_argument("--out"); ap.add_argument("--spec")
    a = ap.parse_args()
    try:
        v1 = yaml.safe_load(open(a.src, encoding="utf-8")) or {}
    except Exception as e:
        sys.stderr.write(f"convert: {e}\n"); sys.exit(2)
    reqs = list(v1.get("based_on") or [])
    if a.spec:
        try:
            reqs = sorted(set(reqs) | set(re.findall(r"\bREQ-\d{3,}\b", open(a.spec, encoding="utf-8").read())))
        except OSError:
            pass
    boundary, hint = [], []
    for ex in v1.get("existence") or []:
        if isinstance(ex, dict) and len(ex) == 1:
            k = next(iter(ex))
            (hint if k in ("file", "function") else boundary).append(ex)
    acs = []
    for i, r in enumerate(reqs, 1):
        acs.append({"id": f"AC-{r.split('-')[-1]}-a", "req": r, "kind": "mechanical", "ears_type": "event",
                    "observe": "TODO: boundary (route:|cli:|ui:|db_field:|event:)", "given": {}, "expect": {},
                    "needs_completion": "written by convert_v1_to_v2 — fill observe/given/expect and add the unwanted twin, or make it kind: human with judge+evidence"})
    beh = v1.get("behavior") or {}
    v2 = {"schema": 2, "feature": v1.get("feature"), "based_on": reqs,
          "created_at": _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat(),
          "created_by": "acceptance-spec+convert_v1_to_v2", "track": "task",
          "acceptance": acs, "existence": boundary,
          "behavior": beh, "rules": v1.get("rules") or [],
          "constraints": {"forbidden_paths": ["tests/**", "done_when.yaml", "dos.yaml", "contract.yaml", ".done_when.lock"], "mock_allowlist": []},
          "budgets": {"card_retries": 3, "plan_reflows": 2, "task_reflows": 1},
          "spec_drift_threshold": v1.get("spec_drift_threshold") or {"max_fix_loops_before_escalation": 3},
          "cards_hint": {"allowed_files": [e.get("file") for e in hint if "file" in e], "functions": [e.get("function") for e in hint if "function" in e],
                          "note": "file/function existence moved out of the contract (C2); assign to cards.allowed_files"}}
    out = a.out or a.src.replace(".v1", "").replace(".yaml", ".v2.yaml")
    with open(out, "w", encoding="utf-8") as f:
        f.write("# generated by convert_v1_to_v2.py — complete every `needs_completion` AC before G2\n")
        yaml.safe_dump(v2, f, allow_unicode=True, sort_keys=False)
    print(json.dumps({"written": out, "acs_needing_completion": [x["id"] for x in acs], "existence_kept": len(boundary), "moved_to_cards_hint": len(hint),
                      "tests_in_manifest": sum(len((beh.get(t) or {}).get(s) or []) for t in ("unit_tests", "integration_tests") for s in ("example_based", "property_based")) + len(beh.get("e2e_tests") or [])}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
