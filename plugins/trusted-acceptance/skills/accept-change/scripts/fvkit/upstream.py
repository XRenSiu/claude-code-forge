"""Vendored upstream methods: integrity of the copy, and citations to it.

Rules and models are generated by following open-source procedures, not prompts written here:
Quint LLM Kit (quint-modeling), Specula (code analysis, spec generation, fidelity triage),
TLA+ AgentSkills, GitHub Spec Kit (specify / clarify), Formal Verification Skills (fresh
adversarial review), pstack and FizzBee. The AI-DLC `formal-verify` skill keeps those files
verbatim under `upstream/`, with an UPSTREAM.json manifest that pins repository, commit,
license and the sha256 of every file.

Two checks keep that honest:
- `verify` — every listed file is present with the recorded bytes, every project keeps its
  license, and nothing unlisted was added. An edited "upstream" file is not upstream any more.
- `citations` — a generation artifact names the upstream files it followed (project, path,
  sha256). The names must be the ones its kind requires, and with a manifest the hashes must be
  the vendored bytes: a procedure that was changed or never vendored cannot be cited.
"""
from pathlib import Path

from .values import FvError, require, sha_bytes

KIND = "fv-upstream"

QUINT = "quint-llm-kit-plugin/skills/quint-modeling/"
REQUIRED = {
    # Spec Kit clarify (ambiguity taxonomy, <=5 questions) + Quint from-requirements (extraction, scope, granularity)
    "fv-rules-intake": [("spec-kit", "templates/commands/clarify.md"),
                        ("quint-llm-kit", QUINT + "guidelines/from-requirements.md"),
                        ("quint-llm-kit", QUINT + "SKILL.md")],
    # Formal Verification Skills: fresh adversarial spec review contract + shared review policy
    "fv-rules-review": [("fvs", "fv-skills/references/fc-spec-review.md"),
                        ("fvs", "fv-skills/references/review-policy.md")],
    "fv-review-triage": [("fvs", "fv-skills/references/review-policy.md")],
    # Quint review (structural + runtime checks) + Specula granularity audit
    "fv-model-review": [("quint-llm-kit", QUINT + "guidelines/review.md"),
                        ("specula", "skills/spec_generation/references/base-spec-methodology.md")],
    # Specula code analysis handoff + brief coverage self-audit
    "fv-brief-coverage": [("specula", "skills/code_analysis/references/modeling-brief-format.md"),
                          ("specula", "skills/spec_generation/references/brief-coverage-checklist.md")],
    # Specula counterexample fidelity checklist + bug classification
    "fv-cex-triage": [("specula", "skills/tla-checking-workflow/references/spec-fidelity-checklist.md"),
                      ("specula", "skills/bug-classification/guide.md")],
}


class Upstream:
    def __init__(self, manifest):
        from .spec import _keys, load_document
        self.path = Path(manifest).resolve()
        doc = load_document(self.path)
        _keys(doc, ["schema_version", "kind", "modified", "projects"], ["notes"], "upstream manifest")
        require(doc["schema_version"] == 1 and doc["kind"] == KIND, "unsupported upstream manifest (schema_version 1, kind fv-upstream)")
        require(doc["modified"] is False, "upstream manifest must declare modified: false (vendored files are never edited)")
        self.root = self.path.parent
        self.projects = {}
        self.files = {}
        for i, p in enumerate(doc["projects"]):
            _keys(p, ["id", "repo", "commit", "license", "license_file", "license_sha256", "files"], ["notes"], "projects[%d]" % i)
            require(p["id"] not in self.projects, "duplicate upstream project %s" % p["id"])
            require(isinstance(p["commit"], str) and len(p["commit"]) == 40, "project %s: commit must be a full 40-hex sha" % p["id"])
            self.projects[p["id"]] = p
            for j, f in enumerate(p["files"]):
                _keys(f, ["upstream_path", "path", "sha256"], [], "projects[%d].files[%d]" % (i, j))
                require(f["path"] == "%s/%s" % (p["id"], f["upstream_path"]), "file %s must live at <project>/<upstream_path>" % f["path"])
                self.files[(p["id"], f["upstream_path"])] = f

    def _safe(self, rel):
        p = (self.root / rel).resolve()
        require(self.root in p.parents, "manifest path escapes the upstream directory: %s" % rel)
        return p

    def verify(self):
        issues = []
        listed = set()
        for pid, p in self.projects.items():
            lic = self._safe(p["license_file"])
            listed.add(lic)
            if not lic.is_file():
                issues.append("%s: license file %s is missing (the license travels with the copy)" % (pid, p["license_file"]))
            elif sha_bytes(lic.read_bytes()) != p["license_sha256"]:
                issues.append("%s: license file %s was changed" % (pid, p["license_file"]))
            for f in p["files"]:
                fp = self._safe(f["path"])
                listed.add(fp)
                if not fp.is_file():
                    issues.append("%s: %s is missing" % (pid, f["path"]))
                elif sha_bytes(fp.read_bytes()) != f["sha256"]:
                    issues.append("%s: %s differs from the vendored upstream bytes (never edit upstream files; "
                                  "refresh from a new commit instead)" % (pid, f["path"]))
            base = self._safe(pid)
            if base.is_dir():
                for extra in sorted(x for x in base.rglob("*") if x.is_file() and x.resolve() not in listed):
                    issues.append("%s: %s is not in the manifest" % (pid, extra.relative_to(self.root)))
        return {"verdict": "INTACT" if not issues else "TAMPERED", "issues": issues, "manifest": str(self.path),
                "projects": {pid: {"repo": p["repo"], "commit": p["commit"], "license": p["license"], "files": len(p["files"])}
                             for pid, p in sorted(self.projects.items())},
                "digest": sha_bytes(self.path.read_bytes())}

    def cite(self, project, upstream_path):
        f = self.files.get((project, upstream_path))
        require(f is not None, "%s:%s is not vendored" % (project, upstream_path))
        return {"upstream": project, "path": upstream_path, "sha256": f["sha256"]}


def citations(procedure, kind, upstream=None):
    """Issues with an artifact's `procedure` list against what its kind requires."""
    issues = []
    if not isinstance(procedure, list) or not procedure:
        return ["%s names no upstream procedure (procedure: [{upstream, path, sha256}])" % kind]
    cited = {}
    for i, c in enumerate(procedure):
        if not (isinstance(c, dict) and set(c) == {"upstream", "path", "sha256"}):
            issues.append("procedure[%d] must be {upstream, path, sha256}" % i)
            continue
        cited[(c["upstream"], c["path"])] = c["sha256"]
        if upstream is not None:
            f = upstream.files.get((c["upstream"], c["path"]))
            if f is None:
                issues.append("procedure %s:%s is not a vendored upstream file" % (c["upstream"], c["path"]))
            elif f["sha256"] != c["sha256"]:
                issues.append("procedure %s:%s cites other bytes than the vendored copy" % (c["upstream"], c["path"]))
    for need in REQUIRED.get(kind, []):
        if need not in cited:
            issues.append("%s must follow upstream %s:%s (cite it in procedure)" % (kind, need[0], need[1]))
    return issues


def load(manifest):
    if manifest is None:
        return None
    try:
        return Upstream(manifest)
    except OSError as error:
        raise FvError("cannot read upstream manifest: %s" % error) from None


def refresh(manifest, project, clone, commit):
    """Re-copy one project's listed files from a local clone at `commit` and re-pin the hashes.

    The maintainer reviews the resulting diff like any other change; nothing is fetched here."""
    import json
    import shutil
    up = Upstream(manifest)
    require(project in up.projects, "unknown upstream project %s" % project)
    clone = Path(clone).resolve()
    p = up.projects[project]
    pairs = [(p["license_file"].split("/", 1)[1], p["license_file"])] + [(f["upstream_path"], f["path"]) for f in p["files"]]
    for src_rel, dst_rel in pairs:
        src = (clone / src_rel).resolve()
        require(clone in src.parents and src.is_file() and not src.is_symlink(), "%s is not a regular file in the clone" % src_rel)
        shutil.copyfile(src, up._safe(dst_rel))
    doc = json.loads(up.path.read_text(encoding="utf-8"))
    for q in doc["projects"]:
        if q["id"] == project:
            require(isinstance(commit, str) and len(commit) == 40, "--commit must be the full sha the clone is at")
            q["commit"] = commit
            q["license_sha256"] = sha_bytes(up._safe(q["license_file"]).read_bytes())
            for f in q["files"]:
                f["sha256"] = sha_bytes(up._safe(f["path"]).read_bytes())
    up.path.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return Upstream(manifest).verify()
