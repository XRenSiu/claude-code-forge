"""Event-driven verification for pull requests (fast / core / deep tiers).

For each module the change touches (computed from git, see policy.impact):
  E2+  lint, contract-weakening check against the base revision (an unapproved weakening
       fails), qualification (complete check + witnesses + coverage + killed mutants);
  E3   fresh source map + implementation traces that conform to the same model; traces are
       read from `traces` (glob) or regenerated by `trace_command` (argv, no shell, `{out}`
       is replaced by a fresh directory under the CI output).
Missing evidence, a crashed step or a stale mapping is UNSATISFIED, never green.
"""
import glob
import json
import subprocess
from pathlib import Path

from .policy import LEVELS, approved, impact, load_policy
from .values import FvError, require


def _level_ge(a, b):
    return LEVELS.index(a) >= LEVELS.index(b)


def run_ci(policy_path, base, out, tier="auto", all_modules=False, root=None):
    from .contract_diff import diff, sample_universe
    from .qualify import conform, qualify
    from .receipt import make, now, write
    from .sourcemap import git, repo_root, verify
    from .spec import Contract, load_contract, load_document, load_model
    from .trace import check_files
    started = now()
    pol = load_policy(policy_path)
    root = Path(root).resolve() if root else repo_root(Path(policy_path).resolve().parent)
    out = Path(out)
    require(not out.exists() or not any(out.iterdir()), "CI output directory must be new or empty: %s" % out)
    out.mkdir(parents=True, exist_ok=True)
    imp = impact(pol, root, base)
    hit = {m["id"]: m for m in imp["modules"]}
    modules = [m for m in pol["modules"] if all_modules or m["id"] in hit]
    records = []
    for m in modules:
        risk = pol["risks"][m["risk"]]
        level = risk["min_level"]
        tname = risk["tier"] if tier == "auto" else tier
        rec = {"id": m["id"], "risk": m["risk"], "min_level": level, "tier": tname, "reasons": [], "receipts": {},
               "impact": hit.get(m["id"])}
        records.append(rec)
        if tname == "none" or not _level_ge(level, "E2"):
            rec["status"] = "SATISFIED" if not _level_ge(level, "E1") else "DELEGATED"
            rec["note"] = "E1 for this risk class is delivered by the project's own property tests" if level == "E1" else "no formal evidence required"
            continue
        settings = dict(pol["tiers"][tname])
        mdir = out / m["id"]
        mdir.mkdir(parents=True, exist_ok=True)
        try:
            contract = load_contract(root / m["contract"])
            model = load_model(root / m["model"], contract=contract)
            from .generation import model_evidence, requirements_for, rules_evidence
            from .upstream import load as load_upstream
            up = load_upstream(root / pol["upstream"]) if pol.get("upstream") else None
            opt = lambda k: root / m[k] if m.get(k) else None  # noqa: E731
            gen = rules_evidence(contract, requirements_for(contract), root / m["rules_divergence"], root / m["rules_review"],
                                 opt("rules_intake"), opt("rules_review_triage"), up)
            rec["reasons"] += ["rules generation: " + r for r in gen["reasons"]]
            brief = ({"brief": opt("modeling_brief"), "ledger": opt("defect_ledger"), "coverage": opt("brief_coverage")}
                     if m.get("modeling_brief") else None)
            mgen = model_evidence(model, root / m["model_divergence"], m.get("entrance", "spec-first"), opt("calibration"),
                                  opt("model_review"), brief, up)
            rec["reasons"] += ["model generation: " + r for r in mgen["reasons"]]
            if base and (hit.get(m["id"]) or {}).get("contract_changed"):
                shown = git(root, "show", "%s:%s" % (base, m["contract"]), check=False)
                if shown.returncode == 0:
                    old_path = mdir / ("base-contract" + Path(m["contract"]).suffix)
                    old_path.write_text(shown.stdout, encoding="utf-8")
                    old = Contract(load_document(old_path), str(old_path))
                    d = diff(old, contract, model.constants, sample_universe(model, settings["max_states"]))
                    rec["contract_diff"] = {"verdict": d["verdict"], "findings": d["findings"]}
                    if d["verdict"] == "WEAKENED":
                        ap = approved(root / m["approvals"], contract.digest) if m.get("approvals") else None
                        if ap:
                            rec["contract_diff"]["approval"] = ap
                        else:
                            rec["reasons"].append("contract weakened without an approval of digest %s" % contract.digest)
                    elif d["verdict"] == "UNKNOWN":
                        rec["reasons"].append("contract change could not be classified; record an approval or make domains finite")
            q = qualify(model, {"max_states": settings["max_states"], "time_seconds": settings["time_seconds"],
                                "allow_bounded": settings["allow_bounded"], "min_depth": m.get("min_depth"),
                                "auto_mutants": settings["auto_mutants"]})
            if not settings["mutants"]:
                q["result"]["reasons"] = [r for r in q["result"]["reasons"] if "mutant" not in r]
                q["verdict"] = "QUALIFIED" if not q["result"]["reasons"] else "NOT_QUALIFIED"
            receipt = make("qualify", {"model": dict(model.identity(), path=m["model"]), "contract": dict(contract.identity(), path=m["contract"])},
                           dict(q["settings"], tier=tname), q["result"], q["verdict"], "E2", started)
            rec["receipts"]["qualify"] = write(mdir / "qualify.json", receipt)
            rec["reasons"] += q["result"]["reasons"]
            if _level_ge(level, "E3"):
                sm = verify(root / m["source_map"], model)   # the map resolves its own `root:`
                if m.get("vectors"):
                    vec = json.loads((root / m["vectors"]).read_text(encoding="utf-8"))
                    if vec.get("model", {}).get("digest") != model.digest or vec.get("contract", {}).get("digest") != contract.digest:
                        rec["reasons"].append("test vectors %s were generated from another model/contract; regenerate with fv gen-tests" % m["vectors"])
                paths = []
                if m.get("trace_command"):
                    tdir = mdir / "traces"
                    tdir.mkdir()
                    argv = [a.replace("{out}", str(tdir)) for a in m["trace_command"]]
                    run = subprocess.run(argv, cwd=str(root), capture_output=True, timeout=settings["time_seconds"])
                    (mdir / "trace-command.stdout").write_bytes(run.stdout[-1000000:])
                    (mdir / "trace-command.stderr").write_bytes(run.stderr[-1000000:])
                    if run.returncode != 0:
                        rec["reasons"].append("trace_command exited %d (see trace-command.stderr)" % run.returncode)
                    paths = sorted(str(p) for p in tdir.glob("*.jsonl"))
                elif m.get("traces"):
                    paths = sorted(glob.glob(str(root / m["traces"])))
                traces = check_files(model, paths) if paths else {"verdict": "INCOMPLETE", "traces": []}
                c = conform(model, sm, traces)
                from .cli import source_binding
                res = {"source_map": {k: sm[k] for k in ("status", "issues", "drifted_files", "stale", "files", "map_digest")},
                       "traces": traces, "reasons": c["reasons"], "source": source_binding(root, sm), "replays": []}
                receipt = make("conform", {"model": dict(model.identity(), path=m["model"]), "contract": dict(contract.identity(), path=m["contract"])},
                               {"hidden_steps": 0, "tier": tname}, res, c["verdict"], "E3", started)
                rec["receipts"]["conform"] = write(mdir / "conform.json", receipt)
                rec["reasons"] += c["reasons"]
                # step 07 again on every change: the code still honours the implementation contract
                from .implcontract import verify_implementation
                v = verify_implementation(root / m["impl_contract"], model, review=root / m["impl_review"], source_map=root / m["source_map"],
                                          run=True, upstream=up, out_dir=mdir / "impl", timeout=settings["time_seconds"])
                receipt = make("implement", {"model": dict(model.identity(), path=m["model"]), "contract": dict(contract.identity(), path=m["contract"]),
                                             "impl_contract": dict(v["impl_contract"], path=m["impl_contract"])},
                               {"run_tests": True, "tier": tname}, v["result"], v["verdict"], "E3", started)
                rec["receipts"]["implement"] = write(mdir / "implement.json", receipt)
                rec["reasons"] += ["implementation: " + r for r in v["result"]["reasons"]]
        except (FvError, OSError, subprocess.TimeoutExpired, json.JSONDecodeError) as error:
            rec["reasons"].append("verification step failed: %s" % error)
        rec["status"] = "SATISFIED" if not rec["reasons"] else "UNSATISFIED"
    verdict = "SATISFIED" if all(r["status"] in ("SATISFIED", "DELEGATED") for r in records) else "UNSATISFIED"
    achieved = [r["min_level"] for r in records if r["status"] == "SATISFIED"]
    level = max(achieved, key=LEVELS.index) if achieved and verdict == "SATISFIED" else "E0"
    summary = {"impact": imp, "modules": records}
    receipt = make("ci", {"policy": {"path": str(policy_path)}, "base": base}, {"tier": tier, "all": all_modules}, summary, verdict, level, started)
    path = write(out / "ci-receipt.json", receipt)
    return {"verdict": verdict, "receipt": path, "modules": [{k: r.get(k) for k in ("id", "risk", "min_level", "tier", "status", "reasons")} for r in records],
            "unclassified": imp["unclassified"]}
