#!/usr/bin/env python3
"""
verify_pr.py — the mechanical pre-gate for /pr: the PRODUCT (PR body + title + branch diff) must
exhibit the section order, carry a linked issue, verification evidence, AC→evidence mapping, and be
within size limits. Pre-flight facts about the branch are checked from git, not from the model's claim.

Usage:
  verify_pr.py --body BODY.md [--title T] [--base BRANCH] [--remote NAME] [--head HEAD] [--done-when F] [--lock L]
               [--sections MAP.yaml] [--proposal-glob 'change-proposal-*.md'] [--allow-xl] [--skip-preflight]
               [--pre-review]

Exit 0 = pass (flags may remain) · 1 = REJECT · 2 = git/IO error or a malformed --sections map.
Output JSON includes size_class, base / base_source, remote / remote_source.

Mechanical guarantees (REJECT — non-waivable half):
  - body slots: summary / scope(do,dont) / linked_issue(Closes|Fixes|Resolves|Refs #N) / changes /
    verification(≥1 command line in a fenced block or a test-evidence line) / acceptance_mapping /
    risk_rollback / reviewer_focus. Without --sections each slot is the English `## Heading` below.
  - --sections MAP (yaml|json): a team that already has its own PR template maps each SLOT onto its headings
    instead of rewriting the template (dogfood vana-builder V-02: a Chinese emoji template and this gate were
    mutually exclusive). What is checked is that the slot is there, not the spelling of its title:
        slots:
          summary:            {headings: ["🎯 概览"]}
          linked_issue:       {in: title_line, pattern: '#\\d+'}       # in: section (default) | title_line
          verification:       {headings: ["✅ 测试"], evidence: '🟢'}  # evidence: regex for one evidence line
          acceptance_mapping: {headings: ["✅ 测试"]}                  # AC ids may sit in <!-- AC-001 --> comments
          risk_rollback:      {required: false, why: "团队模板没有回滚段；回滚写在 issue"}
    Closed set of slot keys (an unknown key is exit 2, never a silently ignored line). `required: false` needs a
    `why`, and every waived slot is reported as a flag. linked_issue / verification / acceptance_mapping can be
    MOVED but never waived: they are the evidence this gate exists for.
  - --done-when: every `kind: mechanical` AC id appears in the acceptance_mapping slot
  - size_class XL (≥1000 changed lines, lockfiles/generated excluded) → reject unless --allow-xl
  - --title: Conventional Commits shape, ≤72
  - --lock: locked files in base..head diff without a change proposal in the diff → reject
  - plugin version sync (CLAUDE.md 三处 version): `plugins/<p>/skills/**` in the range with
    `plugins/<p>/.claude-plugin/plugin.json`'s version unchanged → reject (--no-version-sync opts out)
  - preflight (unless --skip-preflight): head branch ≠ base; working tree clean; every NON-MERGE commit
    in base..head has a Conventional Commits subject (a merge commit's subject is generated by git, and
    this same preflight orders the author to merge — rejecting it made the gate fail its own advice,
    dogfood 2026-09-06 I-74); not behind <remote>/<base> (flag when it cannot be compared)
  - remote and base are RESOLVED, never assumed (dogfood vana-builder V-03 / V-04: `origin` was a GitLab mirror
    and the default branch was `master`, so the sync check read the wrong remote against a branch that
    does not exist). --remote, else the head branch's tracking remote, else the base branch's, else the
    only remote; several remotes with no tracking info = the check is reported as skipped, not run against
    `origin` by guess. --base, else <remote>/HEAD, else the one of main / master that exists; a defaulted
    base is flagged, because a repository that ships from release branches (v*) must name it.
  - --pre-review: a `## Known issues` section must exist and be either `none` / `无` or a list whose items carry
    a file:line anchor (the findings that survived ≤ 2 self-review rounds are documented for the human reviewer,
    not iterated on forever — agentpatterns self-review loop); an item tagged P0 / A-tier is a REJECT (an A-tier
    finding is fixed, not shipped as a known issue)
Flags: L size; untested; TODO/FIXME in body; Reviewer focus without file refs; draft recommended.
"""
import argparse
import fnmatch
import json
import re
import subprocess
import sys

SUBJECT_RE = re.compile(r"^(feat|fix|docs|style|refactor|perf|test|chore|ci|build|revert|wip)(\([a-z0-9\-./*]+\))?!?: \S")
LINK_RE = re.compile(r"\b(Closes|Fixes|Resolves|Refs)\s+#\d+\b", re.I)
GENERATED = ["package-lock.json", "pnpm-lock.yaml", "yarn.lock", "Cargo.lock", "poetry.lock", "go.sum",
             "*.snap", "*.min.js", "*.min.css", "*.generated.*", "dist/*", "build/*"]

# slot → the built-in heading. Order is the section order the skill writes; a --sections map relocates slots.
DEFAULT_SLOTS = {
    "summary": {"headings": ["Summary"]},
    "scope": {"headings": ["Scope"]},
    "linked_issue": {"headings": ["Linked issue"]},
    "changes": {"headings": ["Changes"]},
    "verification": {"headings": ["Verification"]},
    "acceptance_mapping": {"headings": ["Acceptance mapping"]},
    "risk_rollback": {"headings": ["Risk & rollback"]},
    "reviewer_focus": {"headings": ["Reviewer focus"]},
    "known_issues": {"headings": ["Known issues"]},
}
NEVER_WAIVABLE = ("linked_issue", "verification", "acceptance_mapping")
SLOT_KEYS = {"headings", "required", "why", "in", "pattern", "evidence"}


def git(*args, check=True):
    r = subprocess.run(["git", *args], capture_output=True, text=True)
    if check and r.returncode != 0:
        sys.stderr.write(f"verify_pr: git {' '.join(args)} failed: {r.stderr.strip()}\n"); sys.exit(2)
    return r.stdout


def blob(ref, path):
    r = subprocess.run(["git", "show", f"{ref}:{path}"], capture_output=True, text=True)
    return r.stdout if r.returncode == 0 else None


def json_version(text):
    try:
        return (json.loads(text) or {}).get("version")
    except Exception:
        return None


def frontmatter_version(text):
    if not text or not text.startswith("---"):
        return None
    end = text.find("\n---", 3)
    m = re.search(r"^version:\s*([^\s#]+)\s*$", text[: end if end > 0 else 2000], re.M)
    return m.group(1) if m else None


def version_sync_issues(files, base_ref, head_ref):
    """CLAUDE.md's 三处 version 同步 rule, compiled (dogfood 2026-09-06, I-76).

    A PR range sees the whole delivery, so the bump must be inside it — unlike a single staged commit,
    where CLAUDE.md itself puts the bump in its own `chore:` commit. Seven skill files shipped in one
    run with all three versions frozen; a plugin cache is keyed by version and serves
    `<marketplace>/<plugin>/<version>/`, so nobody installed would ever have received those fixes.

    Returns (hard, soft). Deliberate duplicate of the same function in
    ../../commit/scripts/verify_commit.py — these scripts are self-contained per skill; keep in sync.
    """
    hard, soft = [], []
    touched = {}
    for f in files:
        parts = f.split("/")
        if len(parts) >= 4 and parts[0] == "plugins" and parts[2] == "skills":
            touched.setdefault(parts[1], set()).add(parts[3])
    if not touched:
        return hard, soft
    mk_entries = []
    mk = blob(head_ref, ".claude-plugin/marketplace.json")
    if mk:
        try:
            mk_entries = (json.loads(mk) or {}).get("plugins") or []
        except Exception:
            soft.append("marketplace.json is not readable JSON at the head side — version sync unchecked")
    for plugin, skills in sorted(touched.items()):
        manifest = f"plugins/{plugin}/.claude-plugin/plugin.json"
        head_txt = blob(head_ref, manifest)
        if head_txt is None:
            continue
        base_txt = blob(base_ref, manifest)
        hv, bv = json_version(head_txt), json_version(base_txt)
        if hv is None:
            soft.append(f"{manifest} has no readable `version` — version sync unchecked")
            continue
        if base_txt is not None and hv == bv:
            hard.append(f"plugins/{plugin}/skills/** changed but {manifest} version is still {hv} — "
                        f"bump it (CLAUDE.md 三处 version 同步; a version-keyed plugin cache never "
                        f"delivers an unbumped fix)")
        for e in mk_entries:
            if isinstance(e, dict) and e.get("name") == plugin and e.get("version") != hv:
                hard.append(f"marketplace.json registers {plugin} at {e.get('version')} but {manifest} "
                            f"says {hv} — the registry must match the manifest")
        for s in sorted(skills):
            sp = f"plugins/{plugin}/skills/{s}/SKILL.md"
            ht, bt = blob(head_ref, sp), blob(base_ref, sp)
            if ht is None or bt is None:
                continue
            if frontmatter_version(ht) == frontmatter_version(bt):
                soft.append(f"{sp} frontmatter version unchanged ({frontmatter_version(ht)}) while the "
                            f"skill's content changed — third of the three locations")
    return hard, soft


def sections(md):
    out, cur, buf = {}, None, []
    for line in md.splitlines():
        m = re.match(r"^##\s+(.+?)\s*$", line)
        if m:
            if cur is not None:
                out[cur] = "\n".join(buf)
            cur, buf = m.group(1).strip().lower(), []
        else:
            buf.append(line)
    if cur is not None:
        out[cur] = "\n".join(buf)
    return out


def size_class(n):
    return "XS" if n < 50 else "S" if n < 200 else "M" if n < 500 else "L" if n < 1000 else "XL"


def usage_error(msg):
    sys.stderr.write(f"verify_pr: {msg}\n"); sys.exit(2)


def load_slots(path):
    """→ (slots, waived). Built-in headings unless a --sections map relocates them.

    A malformed map is a usage error (exit 2), not a quieter gate: an unknown slot key that silently evaluates
    to "not configured" is the L8 failure shape again, and a waiver without a reason is a door opened by omission.
    """
    slots = {k: dict(v) for k, v in DEFAULT_SLOTS.items()}
    if not path:
        return slots, []
    try:
        text = open(path, encoding="utf-8").read()
    except OSError as e:
        usage_error(f"cannot read --sections {path}: {e}")
    try:
        import yaml
        data = yaml.safe_load(text)
    except ImportError:
        try:
            data = json.loads(text)
        except ValueError as e:
            usage_error(f"--sections {path}: no pyyaml and not JSON ({e})")
    except Exception as e:
        usage_error(f"--sections {path} is not valid YAML: {e}")
    given = (data or {}).get("slots") if isinstance(data, dict) else None
    if not isinstance(given, dict) or not given:
        usage_error(f"--sections {path}: expected a non-empty `slots:` mapping")
    waived = []
    for name, spec in given.items():
        if name not in DEFAULT_SLOTS:
            usage_error(f"--sections {path}: unknown slot {name!r} (closed set: {', '.join(DEFAULT_SLOTS)})")
        if not isinstance(spec, dict):
            usage_error(f"--sections {path}: slot {name} must be a mapping")
        extra = set(spec) - SLOT_KEYS
        if extra:
            usage_error(f"--sections {path}: slot {name} has unknown keys {sorted(extra)} (closed set: {sorted(SLOT_KEYS)})")
        if spec.get("required") is False:
            if name in NEVER_WAIVABLE:
                usage_error(f"--sections {path}: slot {name} cannot be waived — move it (headings / in:), "
                            "it is the evidence this gate exists for")
            if not str(spec.get("why") or "").strip():
                usage_error(f"--sections {path}: slot {name} is waived without a `why`")
            waived.append(f"slot {name} waived by {path}: {spec['why']}")
        if "in" in spec and spec["in"] not in ("section", "title_line"):
            usage_error(f"--sections {path}: slot {name} `in:` must be section | title_line")
        if spec.get("in") == "title_line" and name != "linked_issue":
            usage_error(f"--sections {path}: only linked_issue can live in the title line")
        for rk in ("pattern", "evidence"):
            if rk in spec:
                try:
                    re.compile(str(spec[rk]))
                except re.error as e:
                    usage_error(f"--sections {path}: slot {name} `{rk}` is not a valid regex: {e}")
        if "headings" in spec and (not isinstance(spec["headings"], list) or not all(isinstance(h, str) and h.strip() for h in spec["headings"])):
            usage_error(f"--sections {path}: slot {name} `headings` must be a list of non-empty strings")
        merged = dict(slots[name]); merged.update(spec)
        slots[name] = merged
    return slots, waived


def slot_text(secs, spec):
    """→ the body of the first heading alias present, or None."""
    for h in spec.get("headings") or []:
        key = h.strip().lower()
        if key in secs:
            return secs[key]
    return None


def slot_label(name, spec):
    hs = spec.get("headings") or []
    return f"## {hs[0]}" if hs else name


def git_out(*args):
    r = subprocess.run(["git", *args], capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else ""


def resolve_remote(explicit, head, base):
    """→ (remote | None, source). Never `origin` by assumption (dogfood vana-builder V-03)."""
    remotes = [r for r in git_out("remote").splitlines() if r.strip()]
    if explicit:
        return (explicit, "explicit") if explicit in remotes else (None, f"--remote {explicit} is not a configured remote {remotes}")
    head_branch = git_out("rev-parse", "--abbrev-ref", head)
    for label, br in (("head branch", head_branch), ("base branch", base)):
        if br and br != "HEAD":
            rem = git_out("config", "--get", f"branch.{br}.remote")
            if rem and rem in remotes:
                return rem, f"{label} {br} tracks {rem}"
    if len(remotes) == 1:
        return remotes[0], "the only remote"
    if not remotes:
        return None, "no remote"
    return None, (f"{len(remotes)} remotes ({', '.join(remotes)}) and neither the head nor the base branch tracks one — "
                  "pass --remote")


def resolve_base(explicit, remote):
    """→ (base, source) or exit 2. Never `main` by assumption (dogfood vana-builder V-04)."""
    if explicit:
        return explicit, "explicit"
    if remote:
        ref = git_out("symbolic-ref", "--short", f"refs/remotes/{remote}/HEAD")
        if ref.startswith(remote + "/"):
            return ref[len(remote) + 1:], f"{remote}/HEAD"
    present = [b for b in ("main", "master") if git_out("rev-parse", "--verify", "--quiet", f"refs/heads/{b}")]
    if len(present) == 1:
        return present[0], f"the only one of main / master that exists"
    usage_error("cannot determine the base branch (no <remote>/HEAD, and main / master are "
                f"{'both present' if present else 'both absent'}) — pass --base")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--body", required=True); ap.add_argument("--title")
    ap.add_argument("--base", help="base branch; default <remote>/HEAD, else the one of main / master that exists")
    ap.add_argument("--remote", help="remote hosting the PR; default the head / base branch's tracking remote")
    ap.add_argument("--sections", help="yaml|json map of PR-body slots onto this repository's own template headings")
    ap.add_argument("--head", default="HEAD"); ap.add_argument("--done-when"); ap.add_argument("--lock")
    ap.add_argument("--proposal-glob", default="change-proposal-*.md"); ap.add_argument("--allow-xl", action="store_true")
    ap.add_argument("--skip-preflight", action="store_true"); ap.add_argument("--pre-review", action="store_true")
    ap.add_argument("--no-version-sync", action="store_true")
    a = ap.parse_args()
    rejects, flags = [], []
    md = open(a.body, encoding="utf-8").read()
    secs = sections(md)
    slots, waived = load_slots(a.sections)
    flags.extend(waived)
    remote, remote_source = resolve_remote(a.remote, a.head, a.base)
    if a.remote and remote is None:
        usage_error(remote_source)
    a.base, base_source = resolve_base(a.base, remote)
    if base_source != "explicit":
        flags.append(f"base defaulted to `{a.base}` ({base_source}) — a repository that ships from release branches "
                     "(v*) must pass --base: the PR goes back to the branch it was cut from")
    required = lambda name: slots[name].get("required", True) is not False
    body_of = {}
    for name in ("summary", "scope", "linked_issue", "changes", "verification", "acceptance_mapping",
                 "risk_rollback", "reviewer_focus"):
        spec = slots[name]
        if not required(name):
            continue
        if spec.get("in") == "title_line":
            first = next((l for l in md.splitlines() if l.strip()), "")
            body_of[name] = first
            continue
        txt = slot_text(secs, spec)
        if txt is None:
            rejects.append(f"section missing: {slot_label(name, spec)}"
                           + (f" (slot {name})" if a.sections else ""))
        else:
            body_of[name] = txt
    if "scope" in body_of:
        for k in ("do", "dont"):
            m = re.search(rf"^\s*[-*]\s*{k}\s*:\s*(.+)$", body_of["scope"], re.M)
            if not m or m.group(1).strip().startswith("<"):
                rejects.append(f"Scope.{k} empty — the scope declaration is the baseline for out-of-scope judgments")
    if "linked_issue" in body_of:
        spec = slots["linked_issue"]
        pat = re.compile(str(spec["pattern"])) if spec.get("pattern") else LINK_RE
        if not pat.search(body_of["linked_issue"]):
            where = "the title line" if spec.get("in") == "title_line" else slot_label("linked_issue", spec)
            want = f"/{spec['pattern']}/" if spec.get("pattern") else "`Closes #N` / `Refs #N`"
            rejects.append(f"Linked issue: {where} needs {want}")
    if "verification" in body_of:
        v = body_of["verification"]
        if slots["verification"].get("evidence"):
            has_cmd = bool(re.search(str(slots["verification"]["evidence"]), v, re.M))
        else:
            has_cmd = bool(re.search(r"```[a-z]*\n\s*\S", v)) or bool(re.search(r"^\s*[-*]\s*\S.*(pass|✅|ok|green|failed on)", v, re.I | re.M))
        if not has_cmd:
            rejects.append("Verification: no command / test evidence line")
        if "untested" in v.lower():
            flags.append("untested — reviewer should run it; draft recommended")
    if "reviewer_focus" in body_of and not re.search(r"[\w/.-]+\.(ts|tsx|js|py|go|rs|java|kt|rb|vue|md|yaml|yml|json)(:\d+)?", body_of["reviewer_focus"]):
        flags.append("Reviewer focus names no file — point at file:line")
    if re.search(r"\b(TODO|FIXME|XXX)\b", md):
        flags.append("TODO/FIXME in body — resolve or move to an issue")
    ki_label = slot_label("known_issues", slots["known_issues"])
    if a.pre_review:
        ki = slot_text(secs, slots["known_issues"])
        if ki is None:
            rejects.append(f"--pre-review: section missing: {ki_label} (surviving self-review findings, or `none`)")
        else:
            body_ = ki.strip()
            items = re.findall(r"^\s*[-*]\s+(.+)$", ki, re.M)
            if not body_ or (not items and not re.search(r"^\s*(none|无|n/a)\b", body_, re.I | re.M)):
                rejects.append("--pre-review: Known issues must list surviving findings (file:line each) or say `none`")
            for it in items:
                if not re.search(r"[\w/.-]+\.(ts|tsx|js|py|go|rs|java|kt|rb|vue|md|yaml|yml|json|sh):\d+", it):
                    rejects.append(f"--pre-review: Known issues item without file:line anchor: {it[:60]!r}")
                if re.search(r"\b(P0|A-tier|tier:\s*A)\b", it, re.I):
                    rejects.append(f"--pre-review: Known issues carries a P0 / A-tier finding — fix it, do not ship it: {it[:60]!r}")
            if items and len(items) > 5:
                flags.append(f"--pre-review: {len(items)} known issues — more than the 5-finding cap; consider splitting the PR")
    elif slot_text(secs, slots["known_issues"]) is not None and not slot_text(secs, slots["known_issues"]).strip():
        flags.append("Known issues section present but empty — write `none` or list items")
    if a.title:
        if not SUBJECT_RE.match(a.title):
            rejects.append(f"title not Conventional Commits: {a.title!r}")
        if len(a.title) > 72:
            rejects.append("title > 72 chars")

    # acceptance mapping vs done_when
    if a.done_when:
        try:
            import yaml
            dw = yaml.safe_load(open(a.done_when, encoding="utf-8")) or {}
        except Exception as e:
            sys.stderr.write(f"verify_pr: cannot read done_when: {e}\n"); sys.exit(2)
        # raw slot text, HTML comments included: a template that forbids meta-info in its checklist can still carry
        # `<!-- AC-001 -->` next to the item that evidences it
        table = body_of.get("acceptance_mapping", "")
        for ac in dw.get("acceptance") or []:
            if isinstance(ac, dict) and ac.get("kind") == "mechanical" and ac.get("id") not in table:
                rejects.append(f"Acceptance mapping: {ac.get('id')} (mechanical) has no evidence row")
        for ac in dw.get("acceptance") or []:
            if isinstance(ac, dict) and ac.get("kind") == "human" and ac.get("id") not in table:
                flags.append(f"Acceptance mapping: {ac.get('id')} (human) missing — mark judge/evidence for G3")
    elif "acceptance_mapping" in body_of and not re.search(r"AC-\d", body_of["acceptance_mapping"]):
        flags.append("Acceptance mapping has no AC rows (fine only when no contract exists)")

    # diff size + lock
    rng = f"{a.base}...{a.head}"
    numstat = git("diff", "--numstat", rng, check=False)
    changed, files = 0, []
    for line in numstat.splitlines():
        parts = line.split("\t")
        if len(parts) != 3:
            continue
        add, dele, path = parts
        files.append(path)
        if any(fnmatch.fnmatch(path, g) or fnmatch.fnmatch(path.split("/")[-1], g) for g in GENERATED):
            continue
        changed += (int(add) if add.isdigit() else 0) + (int(dele) if dele.isdigit() else 0)
    sc = size_class(changed)
    if sc == "XL" and not a.allow_xl:
        rejects.append(f"size XL ({changed} lines) — must split (see references/size-and-split.md) or --allow-xl with justification")
    elif sc == "L":
        flags.append(f"size L ({changed} lines) — consider splitting; draft recommended")
    if not a.no_version_sync and files:
        # `base...head` diffs against the merge base, so the version's "before" side is the merge base too —
        # comparing against a base tip that moved on would read a version this branch never started from.
        mb = subprocess.run(["git", "merge-base", a.base, a.head], capture_output=True, text=True)
        vs_hard, vs_soft = version_sync_issues(files, mb.stdout.strip() if mb.returncode == 0 else a.base, a.head)
        rejects.extend(vs_hard); flags.extend(vs_soft)
    if a.lock:
        try:
            lock = json.load(open(a.lock, encoding="utf-8"))
            locked = {e["path"] for e in lock.get("files", [])}
            touched = [f for f in files if f in locked or any(f.startswith(l.rstrip('/') + '/') for l in locked)]
            proposals = [f for f in files if fnmatch.fnmatch(f.split("/")[-1], a.proposal_glob)]
            if touched and not proposals:
                rejects.append(f"locked file(s) changed in {rng} without a change proposal: {touched}")
            elif touched:
                flags.append(f"locked file(s) changed with proposal {proposals} — note in body")
        except Exception as e:
            sys.stderr.write(f"verify_pr: cannot read lock: {e}\n"); sys.exit(2)

    # preflight
    if not a.skip_preflight:
        branch = git("rev-parse", "--abbrev-ref", a.head, check=False).strip()
        if branch == a.base:
            rejects.append(f"head branch is the base branch `{a.base}`")
        if git("status", "--porcelain", check=False).strip():
            rejects.append("working tree not clean — commit or stash first")
        # A merge commit's subject is written by git ("Merge remote-tracking branch …"), and the very next
        # check below tells the author to `merge <remote>/<base>` when behind. Judging that generated subject
        # by Conventional Commits made following this gate's own advice fail this gate (I-74). Parent count
        # is the discriminator: >1 parent = merge. Non-merge subjects are still judged, unchanged.
        commits, subs, merges = 0, [], 0
        for line in git("log", "--format=%P%x09%s", rng, check=False).splitlines():
            if not line.strip():
                continue
            commits += 1
            parents, _, subj = line.partition("\t")
            if len(parents.split()) > 1:
                merges += 1
                continue
            subs.append(subj)
        bad = [s for s in subs if not SUBJECT_RE.match(s)]
        if not commits:
            rejects.append(f"no commits in {rng}")
        if bad:
            rejects.append(f"non-conventional commit subjects in range: {bad[:3]}")
        if merges:
            flags.append(f"{merges} merge commit(s) in range — subjects exempt from the Conventional Commits check")
        if remote is None:
            flags.append(f"sync check skipped: {remote_source}")
        else:
            up = f"{remote}/{a.base}"
            r = subprocess.run(["git", "rev-list", "--count", f"{a.head}..{up}"], capture_output=True, text=True)
            if r.returncode == 0 and r.stdout.strip().isdigit() and int(r.stdout.strip()) > 0:
                rejects.append(f"behind {up} by {r.stdout.strip()} commit(s) — merge {up} first (no rebase)")
            elif r.returncode != 0:
                flags.append(f"could not compare with {up} (not fetched?) — sync check skipped")

    out = {"verdict": "REJECT" if rejects else "PASS", "size_class": sc, "changed_lines": changed, "files": len(files),
           "base": a.base, "base_source": base_source, "remote": remote, "remote_source": remote_source,
           "draft_recommended": bool(flags) or sc in ("L",), "rejects": rejects, "flags": flags}
    print(json.dumps(out, ensure_ascii=False, indent=2))
    sys.exit(1 if rejects else 0)


if __name__ == "__main__":
    main()
